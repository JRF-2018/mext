def esc(s):
    return s.replace('|', '\\|')


def report_md(th, exts, pref, conflicting):
    o = []
    o.append(_t('### 検証の範囲', '### Scope of verification'))
    o.append(scope_text(th, scope(th, exts, pref)) + _t('結論ごとの依存は mext summary・mext sensitivity で調べる。',
                                                       ' Use mext summary and mext sensitivity for the dependencies of each conclusion.'))
    o.append('')
    o.append(_t('### 原子命題', '### Atoms'))
    o.append(_t('| 名前 | 種類 | 文言 | 行 |', '| name | kind | text | lines |'))
    o.append('|---|---|---|---|')
    for a in sorted(th.atoms.values(), key=lambda a: a.id):
        o.append(f'| {a.name} | {a.kind} | {esc(a.text)} | {",".join(str(x) for x in a.lines)} |')
    o.append('')
    o.append(_t('### デフォルト', '### Defaults'))
    o.append(_t('| 名前 | 前提 | 正当化 | 結論 | 種類 | 注 |', '| name | prerequisite | justification | conclusion | kind | note |'))
    o.append('|---|---|---|---|---|---|')
    for d in th.defaults.values():
        o.append(f'| {d.name} | {fmt_lits(th, d.pre)} | {fmt_lits(th, d.just)} | {fmt_lits(th, d.concl)} | {d.kind} | {esc(d.note)} |')
    if th.priority:
        o.append('')
        o.append(_t('優先順位（自動で付けたものを含む）: ', 'Priorities (including automatic ones): ') + ', '.join(f'{a} > {b}' for a, b in sorted(th.priority)))
    o.append('')
    if getattr(th, 'reviews', None):
        o.append(_t('### AI によるあてはめの審査（[ai] の review）', '### Reviews of applications by the AI ([ai] review)'))
        o.append(_t('| 対象 | 判定 | 理由 |', '| target | verdict | reason |'))
        o.append('|---|---|---|')
        label = {'ok': 'ok', 'doubtful': _t('疑わしい', 'doubtful'), 'reject': _t('**棄却**', '**rejected**')}
        for t, (st, note) in th.reviews.items():
            o.append(f'| {esc(t)} | {label[st]} | {esc(note)} |')
        o.append('')
    o.append('### Extension')
    if not exts:
        o.append(_t('Extension は存在しない。', 'There is no Extension.'))
    for i, (E, p) in enumerate(zip(exts, pref), 1):
        tag = _t('（preferred）', ' (preferred)') if p else _t('（preferred ではない）', ' (not preferred)')
        if E == INCONSISTENT:
            o.append(f'- **E{i}**{tag}: ' + _t('矛盾（全リテラル）', 'inconsistent (all literals)'))
            continue
        key = [l for l in sorted(E, key=abs) if th.by_id[abs(l)].kind in ('claim', 'concl')]
        o.append(f'- **E{i}**{tag}: ' + _t('生成デフォルト', 'generating defaults') + f' = {", ".join(generating(th, E))}')
        for l in key:
            o.append(f'  - {esc(th.lit_text(l))}')
    o.append('')
    if th.marks:
        o.append(_t('### 著者の成否（+ / !）との照合', "### Comparison with the author's marks (+ / !)"))
        o.append(_t('| 印 | 対象 | 行 | ', '| mark | target | line | ') + ' | '.join(f'E{i}' for i in range(1, len(exts) + 1)) + ' |')
        o.append('|---|---|---|' + '---|' * len(exts))
        for l, m, line, desc in th.marks:
            cells = []
            for E in exts:
                if E == INCONSISTENT:
                    cells.append('-')
                else:
                    cells.append(_t('一致', 'match') if ((l in E) if m == '+' else (l not in E)) else _t('**不一致**', '**mismatch**'))
            o.append(f'| {m} | {esc(desc)} | {line} | ' + ' | '.join(cells) + ' |')
        o.append('')
    sk, cr = summarize(th, exts, pref)
    o.append(_t('### 懐疑的帰結と信憑的帰結（preferred Extension について）', '### Skeptical and credulous consequences (over preferred Extensions)'))
    if sk is None:
        o.append(_t('- Extension がないため、帰結は定まらない（理論が矛盾しているか、どのデフォルトの組も不動点にならない）',
                    '- No consequences, since there is no Extension (the theory is inconsistent, or no set of defaults is a fixed point)'))
    else:
        key = [l for l in sorted(cr, key=abs) if th.by_id[abs(l)].kind in ('claim', 'concl')]
        sep = ', ' if _en() else '、'
        o.append(_t('- 懐疑的（すべての preferred Extension で成り立つ）: ', '- Skeptical (in every preferred Extension): ')
                 + (sep.join(esc(th.lit_text(l)) for l in key if l in sk) or _t('なし', 'none')))
        o.append(_t('- 信憑的（いずれかの preferred Extension で成り立つ）: ', '- Credulous (in some preferred Extension): ')
                 + (sep.join(esc(th.lit_text(l)) for l in key) or _t('なし', 'none')))
    for n in th.notes:
        o.append(_t('- 注: {n}', '- Note: {n}', n=n))
    return '\n'.join(o)


def cmd_explain(args):
    mf = MextFile(args.file).load()
    th, _ = build(mf)
    exts, pref, _ = solve(th)
    idx = int(args.ext.lstrip('E')) - 1
    if not 0 <= idx < len(exts):
        print(_t('Extension {e} はありません（{n} 個）', 'no Extension {e} (there are {n})', e=args.ext, n=len(exts)))
        return 1
    E = exts[idx]
    errs = []
    l = lit_from_text(th, args.literal, errs)
    if l is None:
        print('\n'.join(errs))
        return 1
    text = '\n'.join(explain_lines(th, l, E, depth_limit=args.depth))
    if getattr(args, 'output', None):
        with open(args.output, 'w', encoding='utf-8') as f:
            f.write(text + '\n')
        print(_t('{o} を書き出しました', 'wrote {o}', o=args.output))
    else:
        print(text)
    return 0


def supports(th, l, E):
    """E の中で l を導く根拠をすべて挙げる（確定事実・規則・生成デフォルト）"""
    out = []
    if l in th.W:
        out.append(('W', None))
    for i, r in enumerate(th.rules):
        if r.head == l and all(b in E for b in r.body):
            out.append(('rule', i))
    gd = set(generating(th, E))
    for d in th.defaults.values():
        if d.name in gd and l in d.concl:
            out.append(('default', d.name))
    return out


def explain_lines(th, l, E, depth=0, seen=None, depth_limit=8):
    """l が E に含まれるならその導出（すべての根拠）を、含まれないなら含まれない理由をたどる"""
    seen = set() if seen is None else seen
    pad = '  ' * depth
    head = f'{pad}{th.lit_str(l)} ' + (f'“{th.lit_text(l)}”' if _en() else f'「{th.lit_text(l)}」')
    if E == INCONSISTENT:
        return [head + _t(' … Extension が矛盾（全リテラル）なので自明に含まれる', ' … trivially included, since the Extension is inconsistent')]
    if depth > depth_limit:
        return [head + _t(' …（深さの上限）', ' … (depth limit)')]
    if l in seen:
        return [head + _t(' …（上に既出）', ' … (shown above)')]
    seen.add(l)
    out = []
    if l in E:
        sups = supports(th, l, E)
        # 根拠が他のリテラルを経由しない順（W を先頭）に並べる
        for k, (kind, ref) in enumerate(sups):
            tag = '' if len(sups) == 1 else _t('［根拠 {a}/{b}］', ' [ground {a}/{b}]', a=k + 1, b=len(sups))
            if kind == 'W':
                out.append(head + _t(' ← 確定事実 W ', ' ← fact in W ') + tag)
            elif kind == 'rule':
                r = th.rules[ref]
                out.append(head + _t(' ← 規則 r{i}（{n}）', ' ← rule r{i} ({n})', i=ref + 1, n=r.note) + tag)
                for b in r.body:
                    out += explain_lines(th, b, E, depth + 1, seen, depth_limit)
            else:
                d = th.defaults[ref]
                js = ', '.join(th.lit_str(j) for j in d.just)
                out.append(head + _t(' ← デフォルト {d}（{n}。正当化 {j} は E と無矛盾）', ' ← default {d} ({n}; justification {j} is consistent with E)',
                                     d=d.name, n=d.note, j=js) + tag)
                for p in d.pre:
                    out += explain_lines(th, p, E, depth + 1, seen, depth_limit)
                if d.kind == 'failure':
                    # 不成立からの結論: 主張 k が E に含まれない理由もたどる
                    for j in d.just:
                        if j < 0 and th.by_id[-j].kind in ('claim', 'req', 'issue', 'aux') and -j not in E:
                            out.append(pad + _t('  （主張が成り立たない理由）', '  (why the claim does not hold)'))
                            out += explain_lines(th, -j, E, depth + 2, seen, depth_limit)
        return out
    # --- 含まれない理由
    out.append(head + _t(' はこの Extension に含まれない', ' is not in this Extension'))
    if -l in E:
        out.append(pad + _t('  理由: 否定 {a} 「{b}」 が成り立つ', '  reason: its negation {a} “{b}” holds', a=th.lit_str(-l), b=th.lit_text(-l)))
        out += explain_lines(th, -l, E, depth + 2, seen, depth_limit)
        return out
    cands = 0
    for i, r in enumerate(th.rules):
        if r.head == l:
            cands += 1
            miss = [b for b in r.body if b not in E]
            out.append(pad + _t('  規則 r{i}（{n}）は前提 {m} を欠く', '  rule r{i} ({n}) lacks the premise(s) {m}', i=i + 1, n=r.note, m=", ".join(th.lit_str(b) for b in miss)))
            for b in miss:
                out += explain_lines(th, b, E, depth + 2, seen, depth_limit)
    for d in th.defaults.values():
        if l in d.concl:
            cands += 1
            miss = [p for p in d.pre if p not in E]
            blocked = [j for j in d.just if -j in E]
            if miss:
                out.append(pad + _t('  デフォルト {d}（{n}）は前提 {m} を欠く', '  default {d} ({n}) lacks the prerequisite(s) {m}', d=d.name, n=d.note, m=", ".join(th.lit_str(p) for p in miss)))
                for p in miss:
                    out += explain_lines(th, p, E, depth + 2, seen, depth_limit)
            if blocked:
                out.append(pad + _t('  デフォルト {d}（{n}）は{a}正当化 {j} が E と矛盾するため働かない',
                                    '  default {d} ({n}) is {a}blocked: its justification {j} is inconsistent with E',
                                    d=d.name, n=d.note, a=(_t('さらに', 'also ') if miss else ''), j=', '.join(th.lit_str(j) for j in blocked)))
                for j in blocked:
                    out += explain_lines(th, -j, E, depth + 2, seen, depth_limit)
    if cands == 0:
        if abs(l) in th.rejected:
            out.append(pad + _t('  この評価のデフォルトは [ai] の review で棄却された（reject）ため、導かれない',
                                '  not derived: the default of this evaluation was rejected by an [ai] review'))
        else:
            out.append(pad + _t('  これを導く規則・デフォルトがない（あてはめる事実が書かれていない）',
                                '  no rule or default derives it (no fact is applied to it)'))
    return out


def cmd_lean(args):
    mf = MextFile(args.file).load()
    th, _ = build(mf)
    exts, pref, _ = solve(th)
    ns = args.namespace or re.sub(r'\W', '_', os.path.splitext(os.path.basename(args.file))[0]).capitalize()
    src = lean_source(th, exts, ns, os.path.basename(args.file), import_spec=args.import_spec)
    out = args.output or os.path.splitext(args.file)[0] + '.lean'
    with open(out, 'w', encoding='utf-8') as f:
        f.write(src)
    print(_t('{o} を書き出しました', 'wrote {o}', o=out))
    return 0


LEAN_PRELUDE = '''/-
  {c_head}
-/
namespace Mext

structure Dflt where
  pre : List Int
  just : List Int
  concl : List Int
deriving Repr

structure Theory where
  W : List Int
  rules : List (List Int × Int)
  defaults : List Dflt

def subsetL (a b : List Int) : Bool := a.all (fun x => b.contains x)

def sameSet (a b : List Int) : Bool := subsetL a b && subsetL b a

def consistentL (S : List Int) : Bool := S.all (fun x => !S.contains (-x))

/-- {c_ok} -/
def okDefaults (T : Theory) (E : List Int) : List Dflt :=
  T.defaults.filter (fun d => d.just.all (fun j => !E.contains (-j)))

/-- {c_step} -/
def step (T : Theory) (ds : List Dflt) (S : List Int) : List Int :=
  let fromRules := (T.rules.filter (fun r => subsetL r.1 S)).map (fun r => r.2)
  let fromDefs := ((ds.filter (fun d => subsetL d.pre S)).map (fun d => d.concl)).flatten
  (S ++ fromRules ++ fromDefs).eraseDups

def iter (T : Theory) (ds : List Dflt) : Nat → List Int → List Int
  | 0, S => S
  | n + 1, S => iter T ds n (step T ds S)

/-- {c_gamma} -/
def gamma (T : Theory) (E : List Int) : List Int :=
  iter T (okDefaults T E) (T.rules.length + T.defaults.length + 1) T.W

/-- {c_ext} -/
def isExtension (T : Theory) (E : List Int) : Bool :=
  consistentL E && sameSet (gamma T E) E

end Mext
'''


def lean_prelude():
    c = {
        'c_head': _t('MEXT の Extension 検証（mext.py が自動生成）\n'
                     '  リテラルは整数で表す: 原子 i は i、その否定は -i。\n'
                     '  Γ(E) を有限回の反復で計算し、Γ(E) = E を decide +kernel（カーネルでの評価）で確かめる。',
                     'Verification of MEXT Extensions (generated by mext)\n'
                     '  Literals are integers: atom i is i, its negation -i.\n'
                     '  Γ(E) is computed by finitely many iterations, and Γ(E) = E is checked by decide +kernel (evaluation in the kernel).'),
        'c_ok': _t('E に照らして正当化が無矛盾なデフォルト', 'defaults whose justifications are consistent with E'),
        'c_step': _t('1 ステップ: 規則と（前提が満たされた）デフォルトの結論を加える',
                     'one step: add the heads of rules and the conclusions of defaults (whose prerequisites hold)'),
        'c_gamma': _t('Γ(E)（反復回数は規則とデフォルトの数 + 1 で十分）',
                      'Γ(E) (the number of rules and defaults + 1 iterations suffice)'),
        'c_ext': _t('E は Extension か（無矛盾で、Γ(E) = E）', 'whether E is an Extension (consistent, and Γ(E) = E)'),
    }
    out = LEAN_PRELUDE
    for k, v in c.items():
        out = out.replace('{' + k + '}', v)
    return out


def lean_source(th, exts, ns, fname, import_spec=False):
    def ll(ls):
        return '[' + ', '.join(str(x) for x in ls) + ']'
    head = (f'import {import_spec}\n\n/- ' + _t('MEXT の Extension 検証（mext.py が自動生成）。検査器と健全性定理は {m} にある。',
                                                 'Verification of MEXT Extensions (generated by mext). The checker and the soundness '
                                                 'theorem are in {m}.', m=import_spec) + ' -/\n') if import_spec else lean_prelude()
    lines = [head, f'namespace Mext.{ns}', '', '/-! ' + _t('{f} の原子命題', 'atoms of {f}', f=fname)]
    for a in sorted(th.atoms.values(), key=lambda a: a.id):
        lines.append(f'  {a.id} = {a.name}: {a.text.replace("-/", "- /")}')
    lines.append('-/')
    lines.append('')
    lines.append('def T : Mext.Theory where')
    lines.append(f'  W := {ll(th.W)}')
    lines.append('  rules := [' + ', '.join(f'({ll(r.body)}, {r.head})' for r in th.rules) + ']')
    lines.append('  defaults := [')
    ds = list(th.defaults.values())
    for i, d in enumerate(ds):
        sep = ',' if i < len(ds) - 1 else ''
        lines.append(f'    ⟨{ll(d.pre)}, {ll(d.just)}, {ll(d.concl)}⟩{sep}  -- {d.name}')
    lines.append('  ]')
    lines.append('')
    for i, E in enumerate(exts, 1):
        if E == INCONSISTENT:
            lines.append('-- ' + _t('E{i} は矛盾した Extension（省略）', 'E{i} is an inconsistent Extension (omitted)', i=i))
            continue
        lst = sorted(E, key=lambda l: (abs(l), l < 0))
        lines.append(f'def E{i} : List Int := {ll(lst)}')
        lines.append(f'theorem E{i}_isExtension : Mext.isExtension T E{i} = true := by decide +kernel')
        if import_spec:
            lines.append('/-- ' + _t('E{i} は Reiter の Extension である（健全性定理による）',
                                     'E{i} is a Reiter Extension (by the soundness theorem)', i=i) + ' -/')
            lines.append(f'theorem E{i}_reiter : Mext.ReiterExtension T E{i} := Mext.isExtension_sound T E{i} E{i}_isExtension')
        lines.append('')
    lines.append(f'end Mext.{ns}')
    return '\n'.join(lines) + '\n'


