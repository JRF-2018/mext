class AIDirectives:
    def __init__(self):
        self.same = {}      # 文言 -> 代表の文言
        self.neg = {}       # 文言 B -> 文言 A （B は ¬A）
        self.failure = set()
        self.effect = set()
        self.review = {}    # 評価デフォルトの文言 "事実@評価" -> (ok|doubtful|reject, 注)
        self.concerns = {}  # 争点の名前 -> ([前提の文言], 注)。内容の上で一つの争点を共有する前提の組（感度分析で使う）
        self.distincts = [] # ([前提の文言], 注)。内容の上で互いに独立だと AI が判断した前提の組
        self.connectives = {}  # 対象（主張のラベル・要件の文言・L行番号）-> (明示|読み, 注)。結び方（AND/OR）が原文に明示されているか
        self.fact_kinds = {}   # 事実の文言 -> (記述|仮定|確認済み|著者の主張, 注)
        self.supplied = {}     # 前提の文言 -> 注。原文になく、書き起こした者が補った前提
        self.extra = []     # (種類, 内容, 注)
        self.raw = []       # 元の行（書き戻し用）

    def canon(self, text):
        seen = set()
        while text in self.same and text not in seen:
            seen.add(text)
            text = self.same[text]
        return text


# .mext の文字列: "…"（中の " と \ は \" \\ と書く）か '…'（文言に " を含み ' を含まないとき）
QSTR = r'"((?:[^"\\]|\\.)*)"|(?<![^\s,&(:/\-!¬])\'((?:[^\'\\]|\\.)*)\''
QRE = re.compile(QSTR)


def unq(m):
    """QRE の一致から文言を得る（\\" などのエスケープを戻す）"""
    t = m.group(1) if m.group(1) is not None else m.group(2)
    return re.sub(r'\\(.)', r'\1', t)


def qs(text):
    """文言を .mext の文字列として書く"""
    if '"' in text and "'" not in text:
        return f"'{text}'"
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def mentions(line, text):
    """行が文言を（エスケープした形も含めて）含むか"""
    return text in line or qs(text)[1:-1] in line


def split_unquoted(s, seps):
    """文字列（"…" と '…'）の外にある seps の文字の位置を返す"""
    out, i, start = [], 0, 0
    while i < len(s):
        m = QRE.match(s, i) if s[i] in '"\'' else None
        if m:
            i = m.end()
            continue
        if s[i] in seps:
            out.append(i)
        i += 1
    return out


FACT_KINDS = ('記述', '仮定', '確認済み', '著者の主張')
FACT_KIND_EN = {'description': '記述', 'assumption': '仮定', 'verified': '確認済み', 'author-claim': '著者の主張'}
FACT_KIND_JA2EN = {v: k for k, v in FACT_KIND_EN.items()}
CONNECTIVE_EN = {'explicit': '明示', 'reading': '読み'}


def split_words(s):
    """空白で区切った語と文字列: (語のリスト, 文字列だったか)"""
    words, quoted = [], []
    for m in re.finditer(QSTR + r'|(\S+)', s):
        q = m.group(3) is None
        words.append(unq(m) if q else m.group(3))
        quoted.append(q)
    return words, quoted


def parse_ai_line(line, ai, lineno, errs):
    body, note = split_note(line)
    s = body.strip()
    if not s:
        return
    words, quoted = split_words(s)
    cmd = words[0] if words else ''
    try:
        if cmd == 'same' and len(words) == 3:
            ai.same[words[2]] = words[1]
        elif cmd == 'neg' and len(words) == 3:
            ai.neg[words[2]] = words[1]
        elif cmd == 'failure' and len(words) == 2:
            ai.failure.add(words[1])
        elif cmd == 'effect' and len(words) == 2:
            ai.effect.add(words[1])
        elif cmd == 'review' and len(words) == 3 and words[2] in ('ok', 'doubtful', 'reject'):
            ai.review[words[1]] = (words[2], note)
        elif cmd == 'concern' and len(words) >= 4 and not quoted[1] and all(quoted[2:]):
            ai.concerns[words[1]] = (words[2:], note)
        elif cmd == 'distinct' and len(words) >= 3 and all(quoted[1:]):
            ai.distincts.append((words[1:], note))
        elif cmd == 'supplied' and len(words) >= 2 and all(quoted[1:]):
            for w in words[1:]:
                ai.supplied[w] = note
        elif cmd == 'connective' and len(words) == 3 and (words[2] in ('明示', '読み') or words[2] in CONNECTIVE_EN):
            ai.connectives[words[1]] = (CONNECTIVE_EN.get(words[2], words[2]), note)
        elif cmd == 'fact-kind' and len(words) == 3 and (words[2] in FACT_KINDS or words[2] in FACT_KIND_EN):
            ai.fact_kinds[words[1]] = (FACT_KIND_EN.get(words[2], words[2]), note)
        else:
            errs.append(_t('[ai] {n} 行目を解釈できません: {l}', '[ai] cannot parse line {n}: {l}', n=lineno, l=line.strip()))
    except IndexError:
        errs.append(_t('[ai] {n} 行目を解釈できません: {l}', '[ai] cannot parse line {n}: {l}', n=lineno, l=line.strip()))


def has_eval(n):
    """事実の部分に @評価 があるか"""
    if n is None:
        return False
    if getattr(n, 'eval', None):
        return True
    return any(has_eval(x) for x in getattr(n, 'items', []) or [])


def quote_text(n):
    """「」の要件と "" の要件（英語のための Matcha-D の別表記）の文言"""
    if getattr(n, 'qchar', '「') == '"':
        return f'"{n.head}"' + (f' {n.suffix}' if n.suffix else '')   # 英文では接尾の語を空白で区切る
    return f'「{n.head}」{n.suffix or ""}'


def split_note(line):
    """; 以降を注として分ける（文字列の中の ; は除く）"""
    pos = split_unquoted(line, ';')
    if pos:
        return line[:pos[0]], line[pos[0] + 1:].strip()
    return line, ''


