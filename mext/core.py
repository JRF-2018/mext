INCONSISTENT = 'INCONSISTENT'


def consistent(S):
    return not any(-l in S for l in S)


def closure(th, defaults, gate=None):
    """W から規則と（前提が満たされた）デフォルトで閉包を取る。gate(d) が偽のデフォルトは使わない。
    戻り値: (集合, 導出の記録)"""
    S = set(th.W)
    why = {l: ('W', None) for l in th.W}
    changed = True
    while changed:
        changed = False
        for i, r in enumerate(th.rules):
            if r.head not in S and all(b in S for b in r.body):
                S.add(r.head)
                why[r.head] = ('rule', i)
                changed = True
        for d in defaults:
            if gate is not None and not gate(d):
                continue
            if all(p in S for p in d.pre) and not all(c in S for c in d.concl):
                for c in d.concl:
                    if c not in S:
                        S.add(c)
                        why[c] = ('default', d.name)
                changed = True
    return S, why


def gamma(th, E):
    """Reiter の Γ(E): E に照らして正当化が無矛盾なデフォルトだけを使った最小の閉包"""
    if E == INCONSISTENT:
        S, why = closure(th, [], None)
        return (S if consistent(S) else INCONSISTENT), why
    ok = [d for d in th.defaults.values() if all(-j not in E for j in d.just)]
    S, why = closure(th, ok)
    return (S if consistent(S) else INCONSISTENT), why


def is_extension(th, E):
    G, _ = gamma(th, E)
    return G == E if E == INCONSISTENT or G == INCONSISTENT else G == E


def generating(th, E):
    if E == INCONSISTENT:
        return []
    return [d.name for d in th.defaults.values()
            if all(p in E for p in d.pre) and all(-j not in E for j in d.just)]


def extensions(th, limit_conflicting=22):
    defs = list(th.defaults.values())
    P, _ = closure(th, defs)            # 正当化を無視した、導出されうるリテラルの上界
    conflicting = [d for d in defs if any(-j in P for j in d.just)]
    safe = [d for d in defs if d not in conflicting]
    if len(conflicting) > limit_conflicting:
        raise RuntimeError(_t('衝突しうるデフォルトが {n} 個あり、全列挙の上限を超えます', '{n} possibly conflicting defaults exceed the limit of full enumeration', n=len(conflicting)))
    found = []
    base, _ = closure(th, [], None)
    if not consistent(base):
        return [INCONSISTENT], conflicting
    for k in range(len(conflicting) + 1):
        for G in itertools.combinations(conflicting, k):
            Gs = set(id(d) for d in G)
            S, _ = closure(th, safe + list(G))
            if not consistent(S):
                continue
            if S in found:
                continue
            if is_extension(th, S):
                found.append(S)
    return found, conflicting


def priority_closure(pairs, names):
    hi = {n: set() for n in names}
    for a, b in pairs:
        if a in hi and b in hi:
            hi[b].add(a)       # a は b より優先
    changed = True
    while changed:
        changed = False
        for b in hi:
            add = set()
            for a in hi[b]:
                add |= hi[a]
            if not add <= hi[b]:
                hi[b] |= add
                changed = True
    return hi   # hi[b] = b より優先されるデフォルトの集合


def preferred(th, E, hi):
    """E が優先順位を尊重して生成できるか（docs/mext.md の定義。Brewka & Eiter 1999 の考え方による）。

    E の生成デフォルトを、前提が満たされた順に一つずつ適用していく列 g1, g2, ... があって、
    各 gi を適用する時点 S で、次の条件が成り立つこと:
      gi より優先されるデフォルト d が E の生成デフォルトでなく、しかも d の前提が（最終的な）E で
      満たされるなら、d はその時点 S ですでに打ち負かされている（d の正当化の否定が S に含まれる）。
    """
    if E == INCONSISTENT:
        return True
    GD = set(generating(th, E))
    defs = th.defaults
    rivals = [d for d in defs.values() if d.name not in GD and all(p in E for p in d.pre)]

    def close_rules(S):
        S = set(S)
        changed = True
        while changed:
            changed = False
            for r in th.rules:
                if r.head not in S and all(b in S for b in r.body):
                    S.add(r.head)
                    changed = True
        return S

    # 各 gi を適用してよいかの条件（前提が S にある、優先する対立デフォルトが S で打ち負かされている）は、
    # S が大きくなっても失われない（単調）。だから適用の順序は結果に効かず、適用できるものを
    # 適用できる限り適用する貪欲な閉包で、条件を満たす列があるかが決まる（以前の深さ優先探索と同じ答えで、指数的にならない）
    S = close_rules(set(th.W))
    applied = set()
    while applied != GD:
        step = [g for g in sorted(GD - applied)
                if all(p in S for p in defs[g].pre)
                and not any(r.name in hi[g] and not any(-j in S for j in r.just) for r in rivals)]
        if not step:
            return False
        for g in step:
            applied.add(g)
            S |= set(defs[g].concl)
        S = close_rules(S)
    return S == E


def solve(th):
    exts, conflicting = extensions(th)
    names = list(th.defaults)
    for a, b in th.priority:
        for x in (a, b):
            if x not in th.defaults:
                th.notes.append(_t('優先順位に未定義のデフォルト {x} があります', 'the priority refers to an undefined default {x}', x=x))
    hi = priority_closure(th.priority, names)
    for n in names:
        if n in hi[n]:
            th.notes.append(_t('優先順位が循環しています（{n}）', 'the priority is cyclic ({n})', n=n))
    pref = [preferred(th, E, hi) for E in exts] if th.priority else [True] * len(exts)
    return exts, pref, conflicting


def final_conclusions(th):
    """最終的な結論: 主張の結論で、その結論も主張自体も、ほかのデフォルトや規則の前提に使われていないもの"""
    used = set()
    for d in th.defaults.values():
        used |= {abs(x) for x in d.pre}
    for r in th.rules:
        used |= {abs(x) for x in r.body}
    out = []
    for d in th.defaults.values():
        if d.kind == 'claim' and len(d.concl) > 1:
            k, c = d.concl[0], d.concl[1]
            if abs(c) not in used and abs(k) not in used and c not in out:
                out.append(c)
    return out


def opposed(th, l):
    """理論の中に l と対立する命題（¬l を結論とするデフォルトか規則）があるか"""
    return any(-l in d.concl for d in th.defaults.values()) or any(r.head == -l for r in th.rules)


def scope(th, exts, pref):
    """検証の範囲: 結果の見栄えが、実際に検証した範囲より強く見えないようにするための数"""
    st = list(getattr(th, 'eval_status', {}).values())
    sk, _ = summarize(th, exts, pref)
    finals = final_conclusions(th)
    fk = getattr(th, 'fact_kinds', {})
    targets = set()
    for doc in getattr(th, 'docs', []) or []:
        stack = [doc]
        while stack:
            n = stack.pop()
            if n.kind == 'claim' and n.facts is not None and n.facts.kind == 'fact':
                targets.add(n.facts.head)      # 主張の対象（<= の右）は事実ではなく、何についての主張かの表示
            stack += [getattr(n, k) for k in ('facts', 'body', 'reason', 'norm', 'application') if getattr(n, k, None) is not None]
            stack += list(getattr(n, 'items', []) or [])
    wf = [th.by_id[abs(l)].text for l in th.W if th.by_id[abs(l)].text not in targets]
    facts = {k: sum(1 for t in wf if fk.get(t, (None,))[0] == k) for k in FACT_KINDS}
    facts['未分類'] = sum(1 for t in wf if t not in fk)
    return {'facts_total': len(wf), 'facts': facts, 'supplied': len(getattr(th, 'supplied', {})),
            'evals': len(st), 'unreviewed': sum(1 for x in st if x is None), 'ok': st.count('ok'),
            'doubtful': st.count('doubtful'), 'reject': st.count('reject'),
            'apps': len(getattr(th, 'app_status', [])),
            'apps_reviewed': [x for x in getattr(th, 'app_status', []) if x[2]],
            'finals': finals, 'finals_hold': [l for l in finals if sk and l in sk],
            'unopposed': [l for l in finals if not opposed(th, l)]}


def scope_text(th, sc):
    """検証の範囲の一行"""
    t = _t('評価 {n} 個（未審査 {u}・ok {o}・doubtful {d}・reject {r}。doubtful と未審査の評価も推論を止めない）。',
           '{n} evaluations (unreviewed {u}, ok {o}, doubtful {d}, reject {r}; doubtful and unreviewed evaluations do not stop inference). ',
           n=sc["evals"], u=sc["unreviewed"], o=sc["ok"], d=sc["doubtful"], r=sc["reject"])
    rv = sc.get('apps_reviewed') or []
    if sc.get('apps') and (rv or not sc['evals']):
        # 評価（@）のないあてはめは確定規則として読まれ、評価の集計に入らない。審査が書かれていれば、その内訳を出す
        cnt = {k: sum(1 for x in rv if x[2] == k) for k in ('ok', 'doubtful', 'reject')}
        t += _t('評価のないあてはめ {n} 個（確定規則として読まれる。review あり {k}: ok {o}・doubtful {d}・reject {r}）。',
                '{n} applications without an evaluation (read as strict rules; reviewed {k}: ok {o}, doubtful {d}, reject {r}). ',
                n=sc['apps'], k=len(rv), o=cnt['ok'], d=cnt['doubtful'], r=cnt['reject'])
    if sc.get('facts_total') and sc['facts']['未分類'] < sc['facts_total']:
        kinds = [(FACT_KIND_JA2EN.get(k, 'unclassified') if _en() else k, v) for k, v in sc['facts'].items() if v]
        t += _t('W の事実 {n} 個（{k}。種別は AI の判断。仮定と著者の主張は感度分析で外す候補にする）。',
                '{n} facts in W ({k}; the kinds are AI judgments; assumptions and author claims are candidates in the sensitivity analysis). ',
                n=sc["facts_total"], k=('・' if not _en() else ', ').join(f'{k} {v}' for k, v in kinds))
    if sc.get('supplied'):
        t += _t('書き起こした者が補った前提 {n} 個（[ai] の supplied。原文にない前提）。',
                '{n} premises supplied by the transcriber ([ai] supplied; not in the source). ', n=sc["supplied"])
    if sc['finals']:
        t += _t('最終的な結論 {n} 個のうち、成り立つもの {h} 個、理論の中に対立する命題（否定）がないもの {u} 個',
                'Of {n} final conclusions, {h} hold and {u} have no opposing proposition (negation) in the theory',
                n=len(sc["finals"]), h=len(sc["finals_hold"]), u=len(sc["unopposed"]))
        if sc['unopposed']:
            t += _t('（これらは、反対の根拠に勝ったのではなく、反対の根拠が書かれていないだけである）',
                    ' (these did not defeat any counter-argument; no counter-argument was written)')
        t += _t('。', '.')
    return t


def summarize(th, exts, pref):
    use = [E for E, p in zip(exts, pref) if p and E != INCONSISTENT]
    if not use:
        return None, None
    sk = set.intersection(*[set(E) for E in use])
    cr = set.union(*[set(E) for E in use])
    return sk, cr


