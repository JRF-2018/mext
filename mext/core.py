class MextFile:
    def __init__(self, path):
        self.path = path
        self.header = []
        self.theory_paths = []
        self.options = set()
        self.ai_lines = []
        self.extra_lines = []
        self.ext_claims = []    # [claimed] に書かれた Extension（検証用）: (名前, preferred?, 文言集合)
        self.claimed_lines = []
        self.sources = {}       # source: 行に記録したファイル -> ハッシュ値
        self.errs = []

    def load(self):
        txt = open(self.path, encoding='utf-8').read()
        sec = None
        for i, ln in enumerate(txt.splitlines(), 1):
            if ln.strip() in (GEN_MARK, GEN_MARK_EN):
                break                      # 以下は自動生成部分なので読まない
            m = re.match(r'^\[(\w+)\]\s*$', ln.strip())
            if m:
                sec = m.group(1)
                continue
            if sec is None:
                self.header.append(ln)
                m2 = re.match(r'^theory:\s*(.+?)\s*$', ln)
                if m2:
                    self.theory_paths.append(split_note(m2.group(1))[0].strip())
                m4 = re.match(r'^source:\s*(\S+)\s+sha256=([0-9a-f]+)', ln)
                if m4:
                    self.sources[m4.group(1)] = m4.group(2)
                m3 = re.match(r'^options:\s*(.*?)\s*$', ln)
                if m3:
                    self.options = set(m3.group(1).split(';')[0].split())
            elif sec == 'ai':
                self.ai_lines.append((i, ln))
            elif sec == 'extra':
                self.extra_lines.append((i, ln))
            elif sec == 'claimed':
                self.claimed_lines.append(ln)
                self.parse_claimed(i, ln)
        return self

    def parse_claimed(self, i, ln):
        body, _ = split_note(ln)
        if not body.strip():
            return
        m = re.match(r'^\s*([^\s*:]+)\s*(\*?)\s*:\s*(.*)$', body)
        if not m:
            self.errs.append(_t('[claimed] {i} 行目を解釈できません', '[claimed] cannot parse line {i}', i=i))
            return
        lits = [x.strip() for x in split_lits(m.group(3))]
        self.ext_claims.append((m.group(1), m.group(2) == '*', lits))

    def theory_files(self):
        base = os.path.dirname(os.path.abspath(self.path))
        if not self.theory_paths:
            raise SystemExit(_t('MEXT に theory: 行がありません', 'the MEXT file has no theory: line'))
        out = []
        for p in self.theory_paths:
            cand = [p, os.path.join(base, p), os.path.join(base, os.path.basename(p))]
            for c in cand:
                if os.path.exists(c):
                    out.append(c)
                    break
            else:
                raise SystemExit(_t('Matcha ファイルが見つかりません: {p}', 'Matcha file not found: {p}', p=p))
        return out


def build(mf, use_review=None):
    if use_review is None:
        use_review = 'no-review' not in mf.options
    ai = AIDirectives()
    for i, ln in mf.ai_lines:
        if use_review or not ln.strip().startswith('review'):
            parse_ai_line(ln, ai, i, mf.errs)
    files = mf.theory_files()
    if len(files) == 1:
        docs, diags, _ = mc.check_text(open(files[0], encoding='utf-8').read())
        docs = [docs]
    else:
        # 複数ファイル: ラベルの名前空間を共有して一つの理論にする。位置は「ファイル名:L12」で示す
        named = [(os.path.splitext(os.path.basename(f))[0], open(f, encoding='utf-8').read()) for f in files]
        docs, diags, _ = mc.check_files(named)
    errs = [d for d in diags if d.level == 'error']
    if errs:
        msg = '\n'.join('  ' + str(d) for d in errs)
        raise SystemExit(_t('Matcha の構文エラーがあるため変換できません:\n{m}', 'cannot translate because of Matcha syntax errors:\n{m}', m=msg))
    th = build_from_docs(mf, ai, files, docs)
    return th, diags


def build_from_docs(mf, ai, files, docs):
    """構文木から理論を作る（結び方の感度分析では、木の AND/OR を入れ替えてから呼ぶ）"""
    comp = Compiler(ai)
    for f, doc in zip(files, docs):
        comp.prefix = os.path.splitext(os.path.basename(f))[0] if len(files) > 1 else ''
        for n in doc.items:
            comp.top(n)
    th = comp.finish()
    extra = []
    for i, ln in mf.extra_lines:
        body, note = split_note(ln)
        m = re.match(r'^\s*(fact|rule|default|priority)\s+(.*)$', body)
        if m:
            extra.append((m.group(1), m.group(2), note, i))
        elif body.strip():
            mf.errs.append(_t('[extra] {i} 行目を解釈できません: {l}', '[extra] cannot parse line {i}: {l}', i=i, l=ln.strip()))
    comp.extra(extra, mf.errs)
    known = set(th.atoms) | set(th.aliases)
    for t in list(ai.same) + list(ai.same.values()) + list(ai.neg) + list(ai.neg.values()) \
            + list(ai.failure) + list(ai.effect) + list(ai.review) + list(ai.fact_kinds):
        if t not in known and ai.canon(t) not in known:
            hint = ''
            if '@' in t:     # 評価の文言なら、同じ「@評価」を持つ原子を候補として示す（書き起こしを直した後の付け替えのため）
                ev = t.rsplit('@', 1)[1]
                cands = [a.text for a in th.atoms.values() if a.kind == 'eval' and a.text.rsplit('@', 1)[-1] == ev]
                if cands:
                    hint = _t('（同じ評価の原子: {c}）', ' (atoms with the same evaluation: {c})', c=', '.join(f'"{c}"' for c in cands[:3]))
            mf.errs.append(_t('[ai] の文言が理論に見当たりません（効いていない可能性があります）: {x}{h}',
                              '[ai] text not found in the theory (it may have no effect): {x}{h}', x=t, h=hint))
    # same / neg は原子の文言で書く必要がある（変換の前に文言を置き換えるため）。別名（ラベルなど）は警告する
    for t in list(ai.same) + list(ai.same.values()) + list(ai.neg) + list(ai.neg.values()):
        if t in th.aliases and t not in th.atoms and t not in comp.texts and not any(th.lit_text(abs(l)) == t for l in th.aliases[t]):
            cands = ', '.join(f'"{th.by_id[abs(l)].text}"' for l in th.aliases[t])
            mf.errs.append(_t('[ai] same / neg の「{x}」は原子の文言ではなく別名です。原子の文言（候補: {c}）で書いてください',
                              '[ai] same / neg “{x}” is an alias, not the text of an atom. Use the text of an atom (candidates: {c})', x=t, c=cands))
    th.reviews = dict(ai.review)
    th.concerns, th.distincts = dict(ai.concerns), list(ai.distincts)
    th.connectives, th.fact_kinds = dict(ai.connectives), dict(ai.fact_kinds)
    th.supplied = dict(ai.supplied)
    th.docs, th.files = docs, files      # lint などが構文木を参照するため
    th.ai = ai
    th.name_atoms()
    return th


def fmt_lits(th, ls):
    return ', '.join(th.lit_str(l) for l in ls) if ls else '⊤'


def render_generated(th, exts, pref, conflicting, diags):
    out = [GEN_MARK_EN if _en() else GEN_MARK]
    unsolved = exts is None
    out.append('[atoms]')
    for a in sorted(th.atoms.values(), key=lambda a: a.id):
        ln = ','.join(str(x) for x in a.lines)
        out.append(f'{a.name:<6} {a.kind:<6} {qs(a.text)}' + (f'  ; {ln}' if ln else ''))
    out.append('')
    out.append('[W]')
    out.append(fmt_lits(th, th.W))
    out.append('')
    out.append('[rules]')
    for i, r in enumerate(th.rules, 1):
        out.append(f'r{i}: {" & ".join(th.lit_str(b) for b in r.body)} -> {th.lit_str(r.head)}  ; {r.note}')
    out.append('')
    out.append('[defaults]')
    for d in th.defaults.values():
        out.append(f'{d.name}: {fmt_lits(th, d.pre)} : {fmt_lits(th, d.just)} / {fmt_lits(th, d.concl)}  ; {d.kind} {d.note}')
    out.append('')
    out.append('[priority]')
    for a, b in sorted(th.priority):
        out.append(f'{a} > {b}')
    out.append('')
    if unsolved:
        out.append('[extensions]')
        out.append(_t('; まだ計算していない（mext.py solve で計算する）', '; not computed yet (run mext solve)'))
        return '\n'.join(out) + '\n'
    out.append('[extensions]')
    out.append(_t('; 衝突しうるデフォルト: {d}', '; possibly conflicting defaults: {d}', d=", ".join(d.name for d in conflicting) or _t('なし', 'none')))
    for i, (E, p) in enumerate(zip(exts, pref), 1):
        tag = ' preferred' if p else ''
        if E == INCONSISTENT:
            out.append(f'E{i}{tag}: INCONSISTENT')
            continue
        out.append(f'E{i}{tag}:')
        out.append(f'  generating: {", ".join(generating(th, E))}')
        out.append(f'  literals: {fmt_lits(th, sorted(E, key=lambda l: (abs(l), l < 0)))}')
    if not exts:
        out.append(_t('; Extension は存在しない', '; there is no Extension'))
    out.append('')
    out.append('[marks]')
    for l, m, line, desc in th.marks:
        res = []
        for i, E in enumerate(exts, 1):
            if E == INCONSISTENT:
                res.append(f'E{i}:-')
                continue
            ok = (l in E) if m == '+' else (l not in E)
            res.append(f'E{i}:' + (_t('一致', 'match') if ok else _t('不一致', 'mismatch')))
        out.append(f'{m} {th.lit_str(l):<6} {line} {desc}  ; {" ".join(res)}')
    out.append('')
    out.append('[summary]')
    sk, cr = summarize(th, exts, pref)
    out.append(f'extensions: {len(exts)} (preferred: {sum(pref)})')
    if sk is None:
        out.append('skeptical: ' + _t('（Extension なし）', '(no Extension)'))
        out.append('credulous: ' + _t('（Extension なし）', '(no Extension)'))
    else:
        key = [l for l in sorted(cr, key=abs) if th.by_id[abs(l)].kind in ('claim', 'concl')]
        out.append('skeptical: ' + (', '.join(th.lit_str(l) for l in key if l in sk) or _t('（主張・結論はなし）', '(no claims or conclusions)')))
        out.append('credulous: ' + (', '.join(th.lit_str(l) for l in key) or _t('（主張・結論はなし）', '(no claims or conclusions)')))
    out.append(_t('; 検証の範囲: ', '; scope of verification: ') + scope_text(th, scope(th, exts, pref)))
    for n in th.notes:
        out.append(_t('; 注: {n}', '; note: {n}', n=n))
    return '\n'.join(out) + '\n'


def file_hash(path):
    import hashlib
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()[:16]


def memo_path(theory_file):
    """書き起こしのメモ（matcha分析の X.matcha.md）"""
    return theory_file + '.md'


def source_lines(mf):
    """元の .matcha と、あれば書き起こしのメモの、ハッシュ値（書き起こしの後に誰かが手を入れたかを見分けるため）"""
    out = []
    base = os.path.dirname(os.path.abspath(mf.path))
    for f in mf.theory_files():
        out.append(f'source: {os.path.relpath(f, base)} sha256={file_hash(f)}')
        m = memo_path(f)
        if os.path.exists(m):
            out.append(f'source: {os.path.relpath(m, base)} sha256={file_hash(m)}')
    return out


def write_mext(mf, th, exts, pref, conflicting, diags):
    hdr = [ln for ln in mf.header if not ln.startswith('source:')]
    idx = max((i + 1 for i, ln in enumerate(hdr) if ln.startswith(('theory:', 'options:'))), default=len(hdr))
    hdr = hdr[:idx] + source_lines(mf) + hdr[idx:]
    mf.header = hdr
    head = '\n'.join(mf.header).rstrip()
    parts = [head, '', '[ai]']
    parts += [ln for _, ln in mf.ai_lines if ln.strip()] or [_t('; （AI の判断をここに書く）', '; (write AI judgments here)')]
    parts += ['', '[extra]']
    parts += [ln for _, ln in mf.extra_lines if ln.strip()] or [_t('; （追加の事実・規則・デフォルト）', '; (additional facts, rules, defaults)')]
    parts += ['', '[claimed]']
    parts += [ln for ln in mf.claimed_lines if ln.strip()] or \
             [_t('; （検証したい Extension を 名前[*]: "文言", -"文言", !"文言" の形で書く。* は preferred）',
                 '; (write Extensions to verify as name[*]: "text", -"text", !"text"; * means preferred)')]
    parts += ['', render_generated(th, exts, pref, conflicting, diags)]
    with open(mf.path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(parts))


